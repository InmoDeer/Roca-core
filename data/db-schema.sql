  id uuid NOT NULL DEFAULT gen_random_uuid(),
  opportunity_id uuid,
  type text NOT NULL CHECK (type = ANY (ARRAY['call'::text, 'whatsapp'::text, 'visit'::text, 'meeting'::text, 'email'::text, 'note'::text])),
  channel text CHECK (channel = ANY (ARRAY['phone'::text, 'whatsapp'::text, 'presencial'::text, 'zoom'::text, 'email'::text, 'none'::text])),
  note text,
  scheduled_at timestamp with time zone,
  completed_at timestamp with time zone,
  created_at timestamp with time zone DEFAULT now(),
  result text,
  status text DEFAULT 'pending'::text CHECK (status = ANY (ARRAY['pending'::text, 'completed'::text, 'cancelled'::text, 'missed'::text])),
  priority integer DEFAULT 1,
  user_id uuid,
  updated_at timestamp with time zone,
  CONSTRAINT activities_pkey PRIMARY KEY (id),
  CONSTRAINT activities_opportunity_id_fkey FOREIGN KEY (opportunity_id) REFERENCES public.opportunities(id),
  CONSTRAINT activities_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id)
);
